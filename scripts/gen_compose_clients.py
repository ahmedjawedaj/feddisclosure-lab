"""Derive a Compose file with N institutions from the certified 3-institution file.

The extra institutions are exact copies of institution 2 with the index changed, so
every isolation rule in compose.flower.yaml (own SuperNode, own ClientApp executor,
one read-only /site mount, one /attestation mount, no ports) applies unchanged.
"""
from __future__ import annotations
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(source: str, clients: int) -> str:
    if clients < 3:
        raise ValueError("At least three institutions are required")
    node = re.search(r"  supernode-2:\n(?:    .*\n)+", source).group(0)
    execu = re.search(r"  clientexec-2:\n(?:    .*\n|      .*\n)+?    depends_on: \[supernode-2\]\n", source).group(0)

    def clone(block: str, i: int) -> str:
        return (block.replace("-2", f"-{i}").replace("_2_", f"_{i}_")
                .replace("partition-id=2", f"partition-id={i}")
                .replace('FDL_SITE_ID: "2"', f'FDL_SITE_ID: "{i}"'))

    out = source.replace(node, node + "".join(clone(node, i) for i in range(3, clients)), 1)
    out = out.replace(execu, execu + "".join(clone(execu, i) for i in range(3, clients)), 1)
    out = out.replace("num-partitions=3", f"num-partitions={clients}")
    header = f"# GENERATED by scripts/gen_compose_clients.py for {clients} institutions. Do not edit by hand.\n"
    return header + out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("clients", type=int)
    p.add_argument("--source", type=Path, default=ROOT / "compose.flower.yaml")
    p.add_argument("--output", type=Path)
    a = p.parse_args()
    out = a.output or ROOT / f"compose.flower.n{a.clients}.yaml"
    out.write_text(generate(a.source.read_text(), a.clients))
    print(out)


if __name__ == "__main__":
    main()
